from sympy import *
init_printing(use_unicode=True)
x = Symbol('x')
M = Matrix([[4,-4,-9,-7,0,7],[3,-1,4,10,8,-2],[2,-3,3,2,-8,7],[5,-4,-2,0,10,-4],[7,9,5,5,4,-7]])
f = M[1,1] * cos(M[1,2]+M[1,3]) + M[1,4] * exp(M[1,5] * x)
print(f.subs(x, 7))
pprint(diff(f,x,2))
pprint(integrate(f,(x,pi,2*sqrt(10))))
A = M.copy()
A.col_del(0)
pprint(A**4)
pprint(A.det())
pprint(A**-1)
pprint(A.eigenvals())
pprint(A.eigenvects())